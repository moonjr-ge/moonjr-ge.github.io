const mobilePlayer = document.querySelector("[data-mobile-player]");
const mobileAudio = mobilePlayer.querySelector("audio");
const mobilePlayButton = mobilePlayer.querySelector("[data-player-toggle]");
const mobilePreviousButton = mobilePlayer.querySelector("[data-player-prev]");
const mobileNextButton = mobilePlayer.querySelector("[data-player-next]");
const mobileTrackTitle = mobilePlayer.querySelector("[data-player-title]");
const mobileTrackTime = mobilePlayer.querySelector("[data-player-time]");
const mobileProgressBar = mobilePlayer.querySelector(".phone-player-progress span");
let mobileTrackIndex = 0;

function formatTime(seconds) {
  if (!Number.isFinite(seconds)) {
    return "0:00";
  }
  return `${Math.floor(seconds / 60)}:${String(Math.floor(seconds % 60)).padStart(2, "0")}`;
}

function loadMobileTrack(index) {
  mobileTrackIndex = index;
  mobileAudio.src = mobilePlaylist[mobileTrackIndex].src;
  mobileTrackTitle.textContent = mobilePlaylist[mobileTrackIndex].title;
  mobileTrackTime.textContent = "0:00";
  mobileProgressBar.style.width = "0%";
}

function playMobileTrack() {
  mobileAudio.play().catch(() => {
    pauseMobileTrack();
  });
  mobilePlayButton.classList.add("is-playing");
  mobilePlayButton.setAttribute("aria-label", "Pause music");
}

function pauseMobileTrack() {
  mobileAudio.pause();
  mobilePlayButton.classList.remove("is-playing");
  mobilePlayButton.setAttribute("aria-label", "Play music");
}

function changeMobileTrack(direction) {
  const wasPlaying = !mobileAudio.paused;
  mobileTrackIndex = (mobileTrackIndex + direction + mobilePlaylist.length) % mobilePlaylist.length;
  loadMobileTrack(mobileTrackIndex);

  if (wasPlaying) {
    playMobileTrack();
  }
}

mobilePlayButton.addEventListener("click", () => {
  if (mobileAudio.paused) {
    playMobileTrack();
  } else {
    pauseMobileTrack();
  }
});

mobilePreviousButton.addEventListener("click", () => {
  changeMobileTrack(-1);
});

mobileNextButton.addEventListener("click", () => {
  changeMobileTrack(1);
});

mobileAudio.addEventListener("timeupdate", () => {
  const progress = mobileAudio.duration ? (mobileAudio.currentTime / mobileAudio.duration) * 100 : 0;
  mobileProgressBar.style.width = `${progress}%`;
  mobileTrackTime.textContent = formatTime(mobileAudio.currentTime);
});

mobileAudio.addEventListener("ended", () => {
  changeMobileTrack(1);
  playMobileTrack();
});

mobileAudio.addEventListener("pause", () => {
  mobilePlayButton.classList.remove("is-playing");
});

mobileAudio.addEventListener("play", () => {
  mobilePlayButton.classList.add("is-playing");
});

loadMobileTrack(mobileTrackIndex);

renderWorkCards();
connectDetailScrollbar(aboutScrollbar, aboutArchive, "y");
updateMobileClock();
setInterval(updateMobileClock, 1000);
restoreFromHash();
