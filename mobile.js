function connectDetailScrollbar(scrollbar, scroller, axis) {
  const thumb = scrollbar.querySelector("span");
  const isHorizontal = axis === "x";

  function updateThumb() {
    const scrollSize = isHorizontal ? scroller.scrollWidth : scroller.scrollHeight;
    const clientSize = isHorizontal ? scroller.clientWidth : scroller.clientHeight;
    const scrollPosition = isHorizontal ? scroller.scrollLeft : scroller.scrollTop;
    const trackSize = (isHorizontal ? scrollbar.clientWidth : scrollbar.clientHeight) - 10;
    const thumbSize = isHorizontal ? thumb.offsetWidth : thumb.offsetHeight;
    const maxScroll = Math.max(0, scrollSize - clientSize);
    const maxTravel = Math.max(0, trackSize - thumbSize);
    const position = maxScroll ? (scrollPosition / maxScroll) * maxTravel : 0;
    thumb.style.transform = isHorizontal ? `translateX(${position}px)` : `translateY(${position}px)`;
  }

  scroller.onscroll = updateThumb;
  scrollbar.onpointerdown = (event) => {
    event.preventDefault();
    scrollbar.setPointerCapture(event.pointerId);
    const startPointer = isHorizontal ? event.clientX : event.clientY;
    const startScroll = isHorizontal ? scroller.scrollLeft : scroller.scrollTop;
    const scrollSize = isHorizontal ? scroller.scrollWidth : scroller.scrollHeight;
    const clientSize = isHorizontal ? scroller.clientWidth : scroller.clientHeight;
    const trackSize = (isHorizontal ? scrollbar.clientWidth : scrollbar.clientHeight) - 10;
    const thumbSize = isHorizontal ? thumb.offsetWidth : thumb.offsetHeight;
    const maxTravel = Math.max(1, trackSize - thumbSize);
    const maxScroll = Math.max(0, scrollSize - clientSize);

    scrollbar.onpointermove = (moveEvent) => {
      const pointer = isHorizontal ? moveEvent.clientX : moveEvent.clientY;
      const nextScroll = startScroll + ((pointer - startPointer) / maxTravel) * maxScroll;
      if (isHorizontal) {
        scroller.scrollLeft = nextScroll;
      } else {
        scroller.scrollTop = nextScroll;
      }
    };

    scrollbar.onpointerup = () => {
      scrollbar.onpointermove = null;
      scrollbar.onpointerup = null;
    };
  };

  requestAnimationFrame(updateThumb);
}

function renderWorkCards() {
  workList.innerHTML = mobileProjects.map((project) => `
    <button class="phone-work-card" type="button" data-project="${project.id}" data-theme="${project.color}">
      <img class="phone-work-card-bg" src="./assets/phone_work_card_bg_${project.color === "purple" ? "01" : "02"}.png" alt="" />
      <img class="phone-work-card-media" src="${project.cardImage}" alt="${project.code}" />
      <span class="phone-work-card-copy">
        <h2>${project.title}</h2>
        <span class="phone-work-card-code">${project.code}</span>
        <span class="phone-work-card-tags">${project.tags.map((tag) => `<span>${tag}</span>`).join("")}</span>
      </span>
    </button>
  `).join("");
}

function showView(viewName, updateHash = true) {
  currentView = viewName;
  views.forEach((view) => {
    view.classList.toggle("is-active", view.dataset.view === viewName);
  });
  shell.classList.toggle("is-home", viewName === "home");

  const activeView = document.querySelector(`[data-view="${viewName}"]`);
  const scroller = activeView?.querySelector(".phone-scroll-content");
  if (scroller) {
    scroller.scrollTop = 0;
  }

  if (updateHash) {
    history.pushState({ view: viewName }, "", `#${viewName}`);
  }
}

function openProject(projectId, updateHash = true) {
  const project = mobileProjects.find((item) => item.id === projectId);
  if (!project) {
    return;
  }

  const detailMedia = project.detailMedia || [project.hero];
  detailHero.innerHTML = `<div class="phone-detail-media-scroll"><div class="phone-detail-track">${detailMedia.map((source) => {
    if (source.endsWith(".mp4")) {
      return `<video src="${source}" autoplay muted loop playsinline aria-label="${project.code}"></video>`;
    }
    return `<img src="${source}" alt="${project.code}" />`;
  }).join("")}</div></div>`;
  detailView.dataset.project = project.id;
  detailView.dataset.theme = project.color;
  detailView.classList.add("is-detail-layout");
  detailTitle.innerHTML = project.title;
  detailCode.textContent = project.code;
  detailDescription.innerHTML = project.description;
  detailTags.innerHTML = project.tags.map((tag) => `<span>${tag}</span>`).join("");
  showView("detail", false);

  const detailMediaScroller = detailHero.querySelector(".phone-detail-media-scroll");
  connectDetailScrollbar(detailScrollbarX, detailMediaScroller, "x");
  connectDetailScrollbar(detailScrollbarY, detailDescription, "y");

  detailDescription.classList.remove("scroll-logo-visible");
  void detailDescription.offsetWidth;
  detailDescription.classList.add("scroll-logo-visible");
  setTimeout(() => detailDescription.classList.remove("scroll-logo-visible"), 2000);

  if (updateHash) {
    history.pushState({ view: "detail", projectId }, "", `#project=${projectId}`);
  }
}

function restoreFromHash() {
  const hash = location.hash.replace(/^#/, "");
  if (hash.startsWith("project=")) {
    openProject(hash.slice(8), false);
    return;
  }

  const route = ["home", "work", "about", "contact"].includes(hash) ? hash : "home";
  showView(route, false);
}

document.addEventListener("click", (event) => {
  const routeButton = event.target.closest("[data-route]");
  if (routeButton) {
    showView(routeButton.dataset.route);
    return;
  }

  const projectButton = event.target.closest("[data-project]");
  if (projectButton) {
    openProject(projectButton.dataset.project);
    return;
  }

  if (event.target.closest("[data-back]")) {
    if (history.length > 1) {
      history.back();
    } else {
      showView(currentView === "detail" ? "work" : "home");
    }
  }
});

window.addEventListener("popstate", restoreFromHash);

function updateMobileClock() {
  const now = new Date();
  clock.textContent = `${String(now.getHours()).padStart(2, "0")}:${String(now.getMinutes()).padStart(2, "0")}`;
}

